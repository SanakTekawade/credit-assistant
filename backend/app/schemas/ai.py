import datetime
from pydantic import BaseModel, Field
from typing import List, Optional

class ActionPlanStep(BaseModel):
    step: int
    title: str
    description: str
    priority: str = Field(..., description="High, Medium, or Low")
    timeframe: str = Field(..., description="e.g. 30 days, 60 days, 3-6 months")

class AIAnalysisRequest(BaseModel):
    force_refresh: Optional[bool] = False

class AIAnalysisResponse(BaseModel):
    summary: str
    health_status: str # Excellent, Good, Fair, Needs Attention, Critical
    key_issues: List[str]
    action_plan: List[ActionPlanStep]
    warnings: List[str]
    disclaimer: str = "This educational analysis is generated by AI based on self-reported financial indicators. It is not professional financial advice, a loan guarantee, or an official credit bureau score report."
    created_at: datetime.datetime = Field(default_factory=datetime.datetime.utcnow)

class AIConsultationHistoryItem(BaseModel):
    id: int
    health_status: Optional[str] = None
    summary: str
    key_issues: List[str]
    action_plan: List[ActionPlanStep]
    warnings: List[str]
    created_at: datetime.datetime

    class Config:
        from_attributes = True
